// Automatic type casting practice

#include <iostream>
using namespace std;

int main(){

    cout << (10/7) << endl;

    cout << (10.0/7) << endl;

    int a = 10;
    float b = 3;

    bool isAdult = true;

    cout << a/b << endl;

    cout << ('A' + 1) << endl;
    cout << 'B' + 1 << endl;

    cout << isAdult + 1 << endl;

    return 0;
}